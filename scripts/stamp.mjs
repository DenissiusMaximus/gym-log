// Writes src/buildInfo.generated.ts with the build time and app version, shown in Settings
// and the developer panel, and stored in backup files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { version } = JSON.parse(
  readFileSync(fileURLToPath(new URL('../package.json', import.meta.url)), 'utf8'),
);

const source =
  `// Generated by scripts/stamp.mjs. Do not edit.\n\n` +
  `export const BUILD_TIME = '${new Date().toISOString()}';\n` +
  `export const APP_VERSION = '${version}';\n`;

const target = fileURLToPath(new URL('../src/buildInfo.generated.ts', import.meta.url));
writeFileSync(target, source);
console.log(`Wrote ${target}`);
