// Generates src/ui/icons.generated.ts from Material Symbols (Rounded, weight 400):
// one SVG path per icon, all sharing the viewBox `0 -960 960 960`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const NAMES = [
  'add',
  'close',
  'check',
  'more_vert',
  'arrow_back',
  'settings',
  'edit',
  'delete',
  'drag_indicator',
  'show_chart',
  'fitness_center',
  'today',
  'event_upcoming',
  'backspace',
  'remove',
  'chevron_left',
  'chevron_right',
  'trending_up',
  'trending_down',
  'trending_flat',
  'archive',
  'unarchive',
  'download',
  'upload',
  'ios_share',
  'expand_more',
  'error',
  'info',
  'warning',
];

// Icons renamed upstream: exported key -> file name in the installed package.
const FILE_ALIASES = { expand_more: 'keyboard_arrow_down' };

const VIEW_BOX = '0 -960 960 960';
const iconDir = new URL('../node_modules/@material-symbols/svg-400/rounded/', import.meta.url);

const entries = NAMES.map((name) => {
  const svg = readFileSync(new URL(`${FILE_ALIASES[name] ?? name}.svg`, iconDir), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  if (viewBox !== VIEW_BOX) throw new Error(`${name}: unexpected viewBox ${viewBox}`);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected 1 path, found ${paths.length}`);
  return `  ${name}: '${paths[0]}',`;
});

const source =
  `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (rounded). Do not edit.\n\n` +
  `export const ICON_VIEW_BOX = '${VIEW_BOX}';\n\n` +
  `export const icons = {\n${entries.join('\n')}\n} as const;\n\n` +
  `export type IconName = keyof typeof icons;\n`;

const target = fileURLToPath(new URL('../src/ui/icons.generated.ts', import.meta.url));
writeFileSync(target, source);
console.log(`Wrote ${NAMES.length} icons to ${target}`);
