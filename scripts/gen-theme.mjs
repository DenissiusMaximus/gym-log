// Generates src/theme/palette.generated.ts: hex values of all MD3 color roles
// for light and dark schemes. Run during development only; the library is not
// part of the runtime bundle.
import { writeFileSync } from 'node:fs';
import { register } from 'node:module';
import { fileURLToPath } from 'node:url';

// @material/material-color-utilities 0.4.0 ships ESM with extensionless relative
// imports, which Node cannot resolve. This hook retries them with a .js suffix.
const hook = `
export async function resolve(specifier, context, next) {
  try {
    return await next(specifier, context);
  } catch (error) {
    if (specifier.startsWith('.') && !specifier.endsWith('.js')) {
      return next(specifier + '.js', context);
    }
    throw error;
  }
}
`;
register('data:text/javascript,' + encodeURIComponent(hook), import.meta.url);

const { Hct, MaterialDynamicColors, SchemeVibrant, argbFromHex, hexFromArgb } = await import(
  '@material/material-color-utilities'
);

const SEED = '#0B57D0';
const CONTRAST = 0;

const ROLES = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'inversePrimary',
  'primaryFixed',
  'primaryFixedDim',
  'onPrimaryFixed',
  'onPrimaryFixedVariant',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'secondaryFixed',
  'secondaryFixedDim',
  'onSecondaryFixed',
  'onSecondaryFixedVariant',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'tertiaryFixed',
  'tertiaryFixedDim',
  'onTertiaryFixed',
  'onTertiaryFixedVariant',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'background',
  'onBackground',
  'surface',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'outline',
  'outlineVariant',
  'inverseSurface',
  'inverseOnSurface',
  'shadow',
  'scrim',
  'surfaceTint',
];

// In 0.4.0 the roles are instance methods; the static properties are deprecated.
const colors = new MaterialDynamicColors();

function buildPalette(isDark) {
  const scheme = new SchemeVibrant(Hct.fromInt(argbFromHex(SEED)), isDark, CONTRAST);
  const out = {};
  for (const role of ROLES) {
    out[role] = hexFromArgb(colors[role]().getArgb(scheme)).toUpperCase();
  }
  return out;
}

function render(name, palette) {
  const lines = Object.entries(palette).map(([k, v]) => `  ${k}: '${v}',`);
  return `export const ${name} = {\n${lines.join('\n')}\n} as const;\n`;
}

const source =
  `// Generated by scripts/gen-theme.mjs (seed ${SEED}, SchemeVibrant, contrast ${CONTRAST}). Do not edit.\n\n` +
  render('light', buildPalette(false)) +
  '\n' +
  render('dark', buildPalette(true)) +
  '\nexport type ColorRole = keyof typeof light;\n';

const target = fileURLToPath(new URL('../src/theme/palette.generated.ts', import.meta.url));
writeFileSync(target, source);
console.log(`Wrote ${target}`);
